/** The drawn size of a mark, in CSS px. */
export const markSize = (id: ValueId) => ({ w: ART[id].w, h: ART[id].h });

/** One mark at its drawn size. It never scales: the panel clips it. */
const ValueMark: React.FC<{ id: ValueId }> = ({ id }) => {
  const art = ART[id];
  const clipId = `value-mark-${useId().replace(/:/g, '')}`;
  // The path list is fixed, so the index is a stable key.
  const shapes = art.paths.map((d, i) => <path key={i} d={d} fill={art.fill} />);
  return (
    <svg
      width={art.w}
      height={art.h}
      viewBox={`0 0 ${art.w} ${art.h}`}
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      focusable="false"
      className="block max-w-none"
    >
      {art.clip ? (
        <>
          <g clipPath={`url(#${clipId})`}>{shapes}</g>
          <defs>
            <clipPath id={clipId}>
              <rect width={art.w} height={art.h} fill="white" />
            </clipPath>
          </defs>
        </>
      ) : (
        shapes
      )}
    </svg>
  );
};

export default ValueMark;
